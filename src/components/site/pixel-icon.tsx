function cells(rows: string[], mark: string) {
  const rects: Array<{ x: number; y: number }> = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x += 1) {
      if (row[x] === mark) rects.push({ x, y });
    }
  });
  return rects;
}

export function PixelIcon({ name, className }: { name: IconName; className?: string }) {
  const rows = MAPS[name];
  return (
    <svg viewBox="0 0 16 16" className={cn("size-8 text-cream", className)} aria-hidden="true" shapeRendering="crispEdges">
      {cells(rows, "#").map((cell) => (
        <rect key={`i${cell.x}-${cell.y}`} x={cell.x} y={cell.y} width="1" height="1" fill="currentColor" />
      ))}
      {cells(rows, "+").map((cell) => (
        <rect key={`a${cell.x}-${cell.y}`} x={cell.x} y={cell.y} width="1" height="1" fill="var(--color-amber)" />
      ))}
    </svg>
  );
}
